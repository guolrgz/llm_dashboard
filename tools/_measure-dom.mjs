import path from 'node:path';
import fs from 'node:fs';
process.env.PLAYWRIGHT_BROWSERS_PATH = path.resolve('browsers');
const libDirs=[path.resolve('libs/usr/lib/x86_64-linux-gnu'),path.resolve('libs/lib/x86_64-linux-gnu')].filter(d=>fs.existsSync(d));
process.env.LD_LIBRARY_PATH=[...libDirs,process.env.LD_LIBRARY_PATH||''].filter(Boolean).join(':');
const { chromium } = await import('playwright');
const b = await chromium.launch({args:['--no-sandbox','--force-color-profile=srgb','--hide-scrollbars','--disable-lcd-text','--font-render-hinting=none']});
const ctx = await b.newContext({viewport:{width:1376,height:768},deviceScaleFactor:2,locale:'zh-CN'});
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:5173/users.html',{waitUntil:'load'});
await p.waitForTimeout(500);
const data = await p.evaluate(() => {
  const r = (el) => { const b = el.getBoundingClientRect(); return {x:+b.x.toFixed(2), y:+b.y.toFixed(2), w:+b.width.toFixed(2), h:+b.height.toFixed(2)}; };
  const out = {};
  out.filterCard = r(document.querySelector('.filter-card') || document.querySelectorAll('.card')[0]);
  out.tableCard = r(document.querySelectorAll('.card')[1]);
  out.input = r(document.querySelector('.search-box, .filter-search, input[type=text]'));
  out.pills = [...document.querySelectorAll('.inline-select, .select-box')].map(r);
  out.pgBtns = [...document.querySelectorAll('.pg-btn')].map(el => ({text: el.textContent.trim(), ...r(el)}));
  out.ellipsis = document.querySelector('.pg-ellipsis') ? r(document.querySelector('.pg-ellipsis')) : null;
  out.pgTotal = document.querySelector('.pg-total') ? r(document.querySelector('.pg-total')) : null;
  out.checkboxes = [...document.querySelectorAll('.chk')].slice(0,3).map(r);
  out.badges = [...document.querySelectorAll('.status-badge')].slice(0,2).map(r);
  out.pillsAction = [...document.querySelectorAll('.row-actions .pill, .action-pill, .row-pill')].slice(0,2).map(r);
  out.tableHead = document.querySelector('.users-table thead') ? r(document.querySelector('.users-table thead')) : null;
  out.rows = [...document.querySelectorAll('.users-table tbody tr')].slice(0,4).map(r);
  out.toolbarBtns = [...document.querySelectorAll('.tb-btn')].map(el => ({text: el.textContent.trim(), ...r(el)}));
  out.pageHead = r(document.querySelector('.page-head'));
  out.h1 = r(document.querySelector('.page-title'));
  out.sub = r(document.querySelector('.page-sub'));
  return out;
});
console.log(JSON.stringify(data,null,1));
await b.close();
